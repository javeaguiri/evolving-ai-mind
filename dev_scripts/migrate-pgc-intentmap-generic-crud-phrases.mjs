// dev_scripts/migrate-pgc-intentmap-generic-crud-phrases.mjs
//
// Sprint 7 Track F1b: split create_domain's generic per-domain CRUD PGC_IntentMap
// rows (intent_category IN add_entity, list_entity, get_entity, update_entity,
// delete_entity — workflow_id IS NULL, one row per action per domain, each a
// pipe-joined 3-phrase pattern) into one row per phrase, matching F1's model for
// create_workflow's own rows.
//
// Scope: only the 5 generic-CRUD intent_categories. The 6 true system rows
// (create_domain, create_workflow, delete_domain, delete_workflow, list_domains,
// help — also workflow_id IS NULL) are untouched: they're managed by
// seed_PGC_IntentMap.json + upsert-intent-map.mjs, which upserts on
// intent_category alone and would fight a split. The generic-CRUD rows are never
// in that seed file — they're written purely at runtime by create_domain step 21,
// so no such conflict exists here.
//
// Source tagging: these phrases are all template-generated by create_domain, not
// user-typed — every migrated (and future) row gets source: 'auto'.
//
// Cleanup compatibility check (already verified, not re-implemented here):
// delete-domain.mjs removes these rows via `pattern LIKE '%<domain>%'` — every
// split single-phrase row still contains the domain name as a substring, so that
// existing cleanup path needs no change and was not touched.
//
// Usage:
//   PGC_DATABASE_URL=<url> node dev_scripts/migrate-pgc-intentmap-generic-crud-phrases.mjs

import pg from 'pg';

const { Client } = pg;

const GENERIC_CRUD_CATEGORIES = ['add_entity', 'list_entity', 'get_entity', 'update_entity', 'delete_entity'];

const PGC_DATABASE_URL = process.env.PGC_DATABASE_URL;
if (!PGC_DATABASE_URL) {
  console.error('ERROR: PGC_DATABASE_URL env var not set');
  process.exit(1);
}

const client = new Client({
  connectionString: PGC_DATABASE_URL,
  connectionTimeoutMillis: 5000,
  ssl: { rejectUnauthorized: false },
});

try {
  await client.connect();
  console.log('Connected to PGC database.\n');

  const rowsResp = await client.query(`
    SELECT id, pattern, intent_category, action_type
    FROM "PGC_IntentMap"
    WHERE workflow_id IS NULL AND intent_category = ANY($1)
  `, [GENERIC_CRUD_CATEGORIES]);

  let splitRowCount = 0;
  let newPhraseCount = 0;

  for (const row of rowsResp.rows) {
    const phrases = row.pattern.split('|').map(p => p.trim().toLowerCase()).filter(p => p.length > 0);
    if (phrases.length <= 1) {
      console.log(`  id ${row.id} (${row.intent_category}): single phrase already — skipping`);
      continue;
    }

    const seen = new Set();
    const uniquePhrases = phrases.filter(p => (seen.has(p) ? false : (seen.add(p), true)));

    await client.query('BEGIN');
    try {
      for (const phrase of uniquePhrases) {
        await client.query(`
          INSERT INTO "PGC_IntentMap" (pattern, intent_category, action_type, source)
          VALUES ($1, $2, $3, 'auto')
        `, [phrase, row.intent_category, row.action_type]);
      }
      await client.query(`DELETE FROM "PGC_IntentMap" WHERE id = $1`, [row.id]);
      await client.query('COMMIT');
    } catch (splitErr) {
      await client.query('ROLLBACK');
      throw splitErr;
    }

    console.log(`  id ${row.id} (${row.intent_category}): split into ${uniquePhrases.length} rows`);
    splitRowCount += 1;
    newPhraseCount += uniquePhrases.length;
  }

  console.log(`\n✅ Migration complete. ${splitRowCount} joined-pattern row(s) split into ${newPhraseCount} phrase row(s).`);

} catch (error) {
  console.error('Migration failed:', error.message);
  process.exit(1);
} finally {
  await client.end();
}
